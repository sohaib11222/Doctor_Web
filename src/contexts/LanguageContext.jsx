const catalogueEntries = Object.entries(englishToItalian).map(([english, italian]) => [english.trim().replace(/\s+/g, ' '), italian])
const toItalian = new Map(catalogueEntries)
const toItalianFolded = new Map(catalogueEntries.map(([english, italian]) => [english.toLocaleLowerCase('en'), italian]))
const toEnglish = new Map(catalogueEntries.map(([english, italian]) => [italian.trim().replace(/\s+/g, ' '), english]))
const toEnglishFolded = new Map(catalogueEntries.map(([english, italian]) => [italian.trim().replace(/\s+/g, ' ').toLocaleLowerCase('it'), english]))

const getByPath = (source, path) => String(path).split('.').reduce((value, part) => value?.[part], source)
const normalise = (value) => String(value).trim().replace(/\s+/g, ' ')

const interpolate = (value, variables) => String(value).replace(/\{(\w+)\}/g, (_, name) => variables[name] ?? `{${name}}`)

const getInitialLanguage = () => {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
  return saved === 'en' || saved === 'it' ? saved : DEFAULT_LANGUAGE
}

const LanguageContext = createContext(null)

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(getInitialLanguage)

  const setLanguage = useCallback((nextLanguage) => {
    const resolvedLanguage = nextLanguage === 'en' ? 'en' : 'it'
    if (typeof window !== 'undefined') window.localStorage.setItem(LANGUAGE_STORAGE_KEY, resolvedLanguage)
    setLanguageState(resolvedLanguage)
  }, [])

  useEffect(() => {
    if (typeof window === 'undefined') return
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const translateText = useCallback((value, targetLanguage = language) => {
    if (value === null || value === undefined || value === '') return value
    const original = String(value)
    const leading = original.match(/^\s*/)?.[0] || ''
    const trailing = original.match(/\s*$/)?.[0] || ''
    const phrase = normalise(original)
    const english = toEnglish.get(phrase) || toEnglishFolded.get(phrase.toLocaleLowerCase('it')) || phrase
    const translated = targetLanguage === 'it' ? (toItalian.get(english) || toItalianFolded.get(english.toLocaleLowerCase('en')) || english) : english
    return `${leading}${translated}${trailing}`
  }, [language])

  const t = useCallback((key, variablesOrFallback = {}, maybeVariables = {}) => {
    const variables = typeof variablesOrFallback === 'object' ? variablesOrFallback : maybeVariables
    const fallback = typeof variablesOrFallback === 'string' ? variablesOrFallback : key
    const translated = getByPath(translations[language], key) ?? getByPath(translations.en, key) ?? fallback
    return interpolate(translated, variables)
  }, [language])

  const locale = language === 'it' ? 'it-IT' : 'en-US'
  const formatDate = useCallback((value, options) => {
    const date = value instanceof Date ? value : new Date(value)
    return Number.isNaN(date.getTime()) ? '' : date.toLocaleDateString(locale, options)
  }, [locale])
  const formatDateTime = useCallback((value, options) => {
    const date = value instanceof Date ? value : new Date(value)
    return Number.isNaN(date.getTime()) ? '' : date.toLocaleString(locale, options)
  }, [locale])

  const value = useMemo(() => ({ language, setLanguage, toggleLanguage: () => setLanguage(language === 'it' ? 'en' : 'it'), t, translateText, formatDate, formatDateTime, translations }), [language, setLanguage, t, translateText, formatDate, formatDateTime])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export const useLanguage = () => {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider')
  return context
}

export default LanguageContext
